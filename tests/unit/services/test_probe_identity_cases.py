"""Every case in miStudio's `probe-identity-cases.json` reproduces here (038 R-039, FTASKS 11.2).

miStudio 039 is the PRODUCER of `mistudio.probe-identity/1` and its case file is the authority:
vendored byte-identically at `docs/schemas/probe-identity-cases.json` and pinned to miStudio's copy
below. A drift in miLLM's projection, defaults, framing or number formatting goes red here, case by
case, with the canonical text that differs.

Three projection differences between S1's reading and miStudio's (038 Review R1 debt 1) were not
exercised by any case. `tests/fixtures/probe_identity_edges.json` carries them with miStudio's OWN
results (generated by miStudio's `document_identity`), so they are pinned too:

(a) `render.bos_handling` projected by its three keys, not hashed whole;
(b) an explicit `null` on a key whose default is not null hashes as `null`;
(c) an absent required block (`model`, `read`, `head`, `aggregation`) hashes as `null`.
"""

from __future__ import annotations

import json
import os
import struct
from pathlib import Path

import pytest

from millm.services import probe_digest
from millm.services.probe_digest import (
    DECISION_V1,
    DEFAULTS,
    DETECTOR_V1,
    IDENTITY_ALGORITHM,
    canonical_bytes,
    decision_payload,
    detector_payload,
    digests_of,
    jcs,
)
from tests.support.sibling_repos import mistudio_repo

REPO = Path(__file__).resolve().parents[3]
VENDORED = REPO / "docs" / "schemas" / "probe-identity-cases.json"
MISTUDIO = mistudio_repo() / "docs" / "schemas" / "probe-identity-cases.json"
EDGES = REPO / "tests" / "fixtures" / "probe_identity_edges.json"
REQUIRED = os.environ.get("MILLM_REQUIRE_CROSS_REPO_CHECKS") == "1"

CASES = json.loads(VENDORED.read_text())
BY_NAME = {case["name"]: case for case in CASES["cases"]}
EDGE_CASES = json.loads(EDGES.read_text())["edges"]


def _canonical(document: dict) -> tuple[str, str]:
    return (canonical_bytes("detector", detector_payload(document)).decode(),
            canonical_bytes("decision", decision_payload(document.get("decision"))).decode())


def test_the_vendored_case_file_is_mistudios_byte_for_byte():
    if not MISTUDIO.exists():
        if REQUIRED:
            pytest.fail(f"MILLM_REQUIRE_CROSS_REPO_CHECKS=1 but miStudio's case file is not at "
                        f"{MISTUDIO}")
        pytest.skip(f"miStudio not checked out at {MISTUDIO}")
    assert VENDORED.read_bytes() == MISTUDIO.read_bytes(), (
        "the vendored identity cases have drifted from miStudio's. Re-vendor; never edit the copy."
    )


def test_the_case_file_names_this_algorithm_and_framing():
    assert CASES["algorithm"] == IDENTITY_ALGORITHM
    assert CASES["framing"]["wrapper"] == {"algorithm": "<algorithm>",
                                           "digest": "detector | decision",
                                           "payload": "<projection>"}
    assert len(CASES["cases"]) >= 70 and len(CASES["numbers"]) >= 100


def test_the_projection_tables_are_the_published_ones():
    """The key lists and the defaults are the case file's, path for path."""
    published = CASES["projection"]
    assert {k: list(v) for k, v in DETECTOR_V1.items()} == published["detector"]["include"]
    assert {k: list(v) for k, v in DECISION_V1.items()} == published["decision"]["include"]
    assert published["detector"]["added_after_v1"] == {} == published["decision"]["added_after_v1"]
    # A default of `null` is what an unlisted absent key already is; the rest must match exactly.
    non_null = {k: v for k, v in published["defaults"].items() if v is not None}
    assert DEFAULTS == non_null
    for path in DEFAULTS:
        assert path in published["defaults"], path


@pytest.mark.parametrize("case", CASES["cases"], ids=lambda c: c["name"])
def test_every_case_reproduces(case):
    detector_text, decision_text = _canonical(case["document"])
    assert detector_text == case["detector_canonical"]
    assert decision_text == case["decision_canonical"]
    assert digests_of(case["document"]) == (case["detector_digest"], case["decision_digest"])


@pytest.mark.parametrize("case", [c for c in CASES["cases"] if c.get("relation")],
                         ids=lambda c: c["name"])
def test_every_stated_relation_holds(case):
    relation = case["relation"]
    other = BY_NAME[relation["to"]]
    mine, theirs = digests_of(case["document"]), digests_of(other["document"])
    for index, half in enumerate(("detector", "decision")):
        assert (mine[index] == theirs[index]) == (relation[half] == "equal"), half


@pytest.mark.parametrize("vector", CASES["numbers"], ids=lambda v: v["bits"])
def test_every_number_vector(vector):
    value = struct.unpack(">d", bytes.fromhex(vector["bits"]))[0]
    assert jcs(value) == vector["jcs"]


@pytest.mark.parametrize("edge", EDGE_CASES, ids=lambda e: e["name"])
def test_the_projection_edges_agree_with_mistudio(edge):
    """R1 debt 1: each edge's expected values are miStudio's own output for the same document."""
    got = digests_of(edge["document"])
    if "refused" in edge:
        # miStudio computes no digest for this document, so miLLM reports NEITHER half (Review
        # R1 6.5, R65-1: the detector half of a null-window document used to be kept).
        assert got == (None, None), edge["about"]
        return
    assert _canonical(edge["document"]) == (edge["detector_canonical"],
                                            edge["decision_canonical"]), edge["about"]
    assert got == (edge["detector_digest"], edge["decision_digest"]), edge["about"]


def _refused_by_mistudio() -> list[tuple[str, dict]]:
    """Documents the hand mirror IMPORTS but miStudio's `document_identity` (main `aacbb153`)
    refuses as a whole — checked by the 6.5 reviewer against miStudio itself, which raised for
    each: `TypeError` for the two non-object `bos_handling` values and the `null` window entry,
    `IdentityInputRefused` for the lone surrogates (no UTF-8 form, so no RFC 8785 bytes). The
    `null` window entry is the one the mirror refuses (`windows` is typed); it is kept because a
    stored row is recomputed by migration `033` and at arm time without the mirror."""
    import copy

    def doc(edit):
        document = copy.deepcopy(BY_NAME["residual"]["document"])
        edit(document)
        return document

    return [
        ("bos-handling-false", doc(lambda d: d["render"].update(bos_handling=False))),
        ("bos-handling-number", doc(lambda d: d["render"].update(bos_handling=1.5))),
        ("surrogate-in-detector", doc(lambda d: d["render"].update(generation_prompt="\ud800"))),
        ("surrogate-in-decision",
         doc(lambda d: d["decision"]["calibration"].update(revision="\ud800"))),
        ("null-window-entry", doc(lambda d: d["decision"].update(windows={"all": None}))),
    ]


@pytest.mark.parametrize("name,document", _refused_by_mistudio(), ids=lambda v: v
                         if isinstance(v, str) else "")
def test_a_document_mistudio_cannot_digest_has_neither_digest_here(name, document):
    """Review R1 (6.5), R65-1: BOTH OR NEITHER. All but the null window entry pass the hand
    mirror (so import reaches `digests_of`), and miStudio reports no identity for any of them;
    6.5 kept the half it could compute and stored it as `computed` — a digest the producer says
    does not exist."""
    from millm.api.schemas.probe import ProbeDefinitionV1

    if name != "null-window-entry":
        ProbeDefinitionV1.model_validate(document)  # reachable through import
    assert digests_of(document) == (None, None), name


def test_the_edges_cover_all_three_r1_differences():
    names = {e["name"] for e in EDGE_CASES}
    assert {"bos-extra-key", "bos-partial"} <= names                       # (a)
    assert {"render-add-special-null", "head-bias-null", "params-null"} <= names  # (b)
    assert {"read-absent", "head-absent", "aggregation-absent", "model-absent"} <= names  # (c)


def test_every_case_document_imports_through_the_hand_mirror():
    """A case is a complete valid document; the mirror (and its typed `identity`) accepts each."""
    from millm.api.schemas.probe import ProbeDefinitionV1

    for case in CASES["cases"]:
        parsed = ProbeDefinitionV1.model_validate(case["document"])
        carried = case["document"].get("identity")
        if carried is not None:
            assert parsed.identity is not None
            assert parsed.identity.model_dump() == {"decision_revision": None, **carried}


def test_the_module_imports_nothing_but_the_standard_library():
    """Migrations carry a frozen copy; the live module must stay copyable (no service import)."""
    source = Path(probe_digest.__file__).read_text()
    imported = [line.split()[1] for line in source.splitlines()
                if line.startswith(("import ", "from ")) and "__future__" not in line]
    assert set(imported) <= {"copy", "hashlib", "json", "math", "typing"}, imported


def test_the_serializer_itself_refuses_an_unsafe_integer():
    """`digests_of` refuses before serialising; `jcs` must refuse on its own too, or a direct
    `detector_digest()` would write 2^53 as a double that names a different integer."""
    from millm.services.probe_digest import NonFiniteNumber, detector_digest

    assert jcs(2 ** 53 - 1) == "9007199254740991"
    with pytest.raises(NonFiniteNumber):
        jcs(2 ** 53)
    with pytest.raises(NonFiniteNumber):
        jcs(-(2 ** 53))
    doc = json.loads(json.dumps(CASES["cases"][0]["document"]))
    doc["aggregation"]["params"] = {"n": 2 ** 60}
    with pytest.raises(NonFiniteNumber):
        detector_digest(doc)
