"""The signal-schema block of the telemetry guide, GENERATED from the live registries (FR-38.26).

The guide (`manual/docs/features/telemetry-export.md`) carries one block between the markers
below. `tests/unit/telemetry/test_signal_schema_doc.py` regenerates it and fails when the
committed block differs, so an instrument, span, record attribute or resource attribute that is
registered but undocumented (or documented but gone) is red — control M27.

Sources, all read at run time, none listed by hand except the prose:
* metric instruments: the instruments registered on a LIVE `MeterProvider` built by the export
  pipeline (`Pipeline(...)`, never started: no thread, no network); counter dimensions from
  `counters.INSTRUMENTS`;
* span names and attributes, record attributes, resource attributes: the allowlist tables
  (`millm.telemetry.allowlist`), which are what may leave;
* the semantic-conventions schema URL: `millm.telemetry.SEMCONV_SCHEMA_URL`.

The hand-written parts are one sentence per span and per histogram dimension list, keyed by
name; a name with no entry (or an entry with no name) raises, so a new span or histogram cannot
be generated without its description.

Regenerate:  venv/bin/python -m tests.support.telemetry_signal_doc --write
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GUIDE = ROOT / "manual" / "docs" / "features" / "telemetry-export.md"
BEGIN = "<!-- signal-schema:begin (generated by tests/support/telemetry_signal_doc.py; do not edit) -->"
END = "<!-- signal-schema:end -->"
#: The probe page carries the published reason-code list, generated the same way.
PROBE_PAGE = ROOT / "manual" / "docs" / "features" / "probe-monitors.md"
REASONS_BEGIN = "<!-- reason-codes:begin (generated by tests/support/telemetry_signal_doc.py; do not edit) -->"
REASONS_END = "<!-- reason-codes:end -->"

#: One line per span name (allowlist.SPAN_NAMES). Keys must equal that set.
SPAN_TEXT = {
    "chat": "One per `/v1/chat/completions` request (streaming: until the stream ends). `ERROR` "
            "on an exception or a client disconnect.",
    "text_completion": "One per `/v1/completions` request.",
    "millm.probe_score": "One per `POST /api/probes/score` call.",
    "millm.queue.wait": "Child: the wait for an admission slot.",
    "millm.probe.evaluate": "Child: probe evaluation at the end of generation. Its span id is "
                            "every result's `span_id`.",
}

#: Histogram dimensions (recorded on the export thread in `telemetry.observe`). Keys must equal
#: the live histograms.
HISTOGRAM_DIMS = {
    "millm.probe.evaluation.duration": ("probe_id", "window", "engine"),
    "millm.probe.score_margin": ("probe_id", "window"),
}

#: The Prometheus unit suffix the backend's OTLP receiver appends (verified on Prometheus 3.15.0
#: in grafana/otel-lgtm 0.38.0, 2026-10-23: `ms` → `_milliseconds`; `1` adds nothing).
UNIT_SUFFIX = {"ms": "_milliseconds", "1": ""}


def live_instruments() -> list[tuple[str, str, str]]:
    """`(name, kind, unit)` of every instrument on a live meter provider of the export pipeline.
    `kind` is `counter`, `histogram` or `exponential_histogram` (the provider's own views)."""
    from millm import telemetry
    from millm.core.config import settings
    from millm.telemetry.pipeline import Pipeline
    from millm.telemetry.settings import load

    cfg = load(settings.model_copy(update={
        "TELEMETRY_METRICS_ENABLED": True, "TELEMETRY_TRACES_ENABLED": False,
        "TELEMETRY_LOGS_ENABLED": False, "TELEMETRY_ENDPOINT": "http://127.0.0.1:9",
        "TELEMETRY_ALLOW_PLAINTEXT": True, "OTEL_SDK_DISABLED": False,
    }))
    pipeline = Pipeline(cfg, "0.0.0", telemetry.SEMCONV_SCHEMA_URL)
    try:
        exponential = {
            v._instrument_name  # noqa: SLF001
            for v in pipeline.meter_provider._sdk_config.views  # noqa: SLF001
            if type(v._aggregation).__name__ == "ExponentialBucketHistogramAggregation"  # noqa: SLF001
        }
        out = []
        for meter in pipeline.meter_provider._meters.values():  # noqa: SLF001 - the live registry
            for inst in meter._instrument_id_instrument.values():  # noqa: SLF001
                kind = ("counter" if "Counter" in type(inst).__name__
                        else "exponential_histogram" if inst.name in exponential else "histogram")
                out.append((inst.name, kind, inst.unit or ""))
        return sorted(out)
    finally:
        pipeline.meter_provider.shutdown()


def prometheus_names(name: str, kind: str, unit: str) -> list[str]:
    """The series names the reference backend stores for an OTLP instrument."""
    base = name.replace(".", "_") + UNIT_SUFFIX.get(unit, "_" + unit)
    if kind == "counter":
        return [base + "_total"]
    if kind == "exponential_histogram":  # stored as a Prometheus native histogram
        return [base]
    return [base + "_bucket", base + "_sum", base + "_count"]


def _code(items) -> str:
    return ", ".join(f"`{i}`" for i in items)


def render() -> str:
    from millm import telemetry
    from millm.telemetry import allowlist, counters

    if set(SPAN_TEXT) != set(allowlist.SPAN_NAMES):
        raise AssertionError(f"SPAN_TEXT {sorted(SPAN_TEXT)} != SPAN_NAMES "
                             f"{sorted(allowlist.SPAN_NAMES)}")
    instruments = live_instruments()
    histograms = {n for n, k, _u in instruments if k != "counter"}
    if histograms != set(HISTOGRAM_DIMS):
        raise AssertionError(f"HISTOGRAM_DIMS {sorted(HISTOGRAM_DIMS)} != live {sorted(histograms)}")

    lines = [BEGIN, "", f"Semantic-conventions schema: `{telemetry.SEMCONV_SCHEMA_URL}`. "
             "Instrumentation scope: `millm`.", ""]
    lines += ["#### Resource attributes", "", _code(sorted(allowlist.RESOURCE)), ""]
    lines += ["#### Spans", "", "| Span name | What it covers |", "|---|---|"]
    for name in sorted(allowlist.SPAN_NAMES):
        lines.append(f"| `{name}` | {SPAN_TEXT[name]} |")
    lines += ["", "Span attributes (each only where it applies): " + _code(sorted(allowlist.SPAN)),
              ""]
    lines += ["#### Metric instruments", "",
              "| Instrument | Kind | Unit | Dimensions | Name in the reference backend |",
              "|---|---|---|---|---|"]
    for name, kind, unit in instruments:
        if name in counters.INSTRUMENTS:
            dims = counters.INSTRUMENTS[name][2]
        elif name in HISTOGRAM_DIMS:
            dims = HISTOGRAM_DIMS[name]
        else:
            dims = ()
        prom = prometheus_names(name, kind, unit)
        shown = "histogram (base-2 exponential)" if kind == "exponential_histogram" else kind
        lines.append(f"| `{name}` | {shown} | `{unit}` | {_code(dims) or 'none'} | "
                     f"{_code(prom)} |")
    lines += ["", "A series beyond `TELEMETRY_SERIES_CAP` is folded into the one series "
              "`otel.metric.overflow=true` and counted in `millm.probe.series_overflow`.", ""]
    lines += ["#### Log records", "",
              f"Event names: {_code(sorted(allowlist.EVENT_NAMES))}. Each is an OpenTelemetry "
              "log record with no body; its trace and span ids are on the record.", "",
              "`mi.probe.result` attributes (the result contract, flattened):", "",
              _code(sorted(allowlist.LOG_RESULT)), "",
              "`mi.probe.lifecycle` attributes:", "", _code(sorted(allowlist.LOG_LIFECYCLE)), "",
              END]
    return "\n".join(lines)


def render_reasons() -> str:
    """The published reason-code table (`millm.services.probe_reasons.REASON_TABLE`)."""
    from millm.services.probe_reasons import REASON_TABLE

    lines = [REASONS_BEGIN, "", "| Reason | Outcome | Means |", "|---|---|---|"]
    order = {"skipped": 0, "failed": 1, "interrupted": 2}
    for code, (outcome, meaning) in sorted(REASON_TABLE.items(),
                                           key=lambda kv: (order[kv[1][0]], kv[0])):
        lines.append(f"| `{code}` | {outcome} | {meaning} |")
    lines += ["", REASONS_END]
    return "\n".join(lines)


def committed_block(text: str, begin: str = BEGIN, end: str = END) -> str | None:
    start, stop = text.find(begin), text.find(end)
    if start < 0 or stop < 0:
        return None
    return text[start:stop + len(end)]


def write() -> None:
    for path, begin, end, fresh in ((GUIDE, BEGIN, END, render()),
                                    (PROBE_PAGE, REASONS_BEGIN, REASONS_END, render_reasons())):
        text = path.read_text()
        old = committed_block(text, begin, end)
        if old is None:
            raise SystemExit(f"markers not found in {path}")
        path.write_text(text.replace(old, fresh))


if __name__ == "__main__":
    if "--write" in sys.argv:
        write()
    else:
        print(render())
